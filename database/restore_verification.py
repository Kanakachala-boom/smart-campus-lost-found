"""
Database Restoration Verification Utility for Smart Campus Lost & Found System
Institution: The National Institute of Engineering (NIE), Mysuru

Verifies that backups generated by backup.py can be successfully restored
into an isolated, disposable database without affecting the live database.
"""

import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BASE_DIR / "backend"))

from app.config import DB_HOST, DB_PORT, DB_NAME, DB_USER, DB_PASSWORD
from sqlalchemy import create_engine, text, inspect

BACKUP_DIR = BASE_DIR / "database" / "backups"
DISPOSABLE_DB = "campus_lost_found_restore_verify_test"

def verify_restoration():
    # Find latest backup file
    backups = sorted(BACKUP_DIR.glob(f"backup_{DB_NAME}_*.sql"), key=lambda p: p.stat().st_mtime, reverse=True)
    if not backups:
        print("[!] No backup files found in database/backups to verify.")
        sys.exit(1)

    latest_backup = backups[0]
    print(f"[*] Testing restoration of: {latest_backup.name}")
    print(f"[*] Target disposable test database: '{DISPOSABLE_DB}'")

    from sqlalchemy import URL

    # Connect to MySQL server (without selecting specific DB)
    server_url = URL.create(
        drivername="mysql+pymysql",
        username=DB_USER,
        password=DB_PASSWORD,
        host=DB_HOST,
        port=DB_PORT,
    )
    server_engine = create_engine(server_url, isolation_level="AUTOCOMMIT")

    with server_engine.connect() as conn:
        print(f"[*] Creating disposable test database `{DISPOSABLE_DB}`...")
        conn.execute(text(f"DROP DATABASE IF EXISTS `{DISPOSABLE_DB}`"))
        conn.execute(text(f"CREATE DATABASE `{DISPOSABLE_DB}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci"))

    # Connect to the disposable database
    test_db_url = URL.create(
        drivername="mysql+pymysql",
        username=DB_USER,
        password=DB_PASSWORD,
        host=DB_HOST,
        port=DB_PORT,
        database=DISPOSABLE_DB,
    )
    test_engine = create_engine(test_db_url)

    try:
        print(f"[*] Executing SQL statements from backup into `{DISPOSABLE_DB}`...")
        with open(latest_backup, "r", encoding="utf-8") as f:
            sql_content = f.read()

        # Split and execute non-empty statements
        statements = [stmt.strip() for stmt in sql_content.split(";\n") if stmt.strip()]
        with test_engine.connect() as conn:
            conn.execute(text("SET FOREIGN_KEY_CHECKS = 0;"))
            for stmt in statements:
                if stmt.startswith("--") or not stmt:
                    continue
                try:
                    conn.execute(text(stmt))
                except Exception as stmt_err:
                    print(f"    [!] Warning on statement: {stmt_err}")
            conn.execute(text("SET FOREIGN_KEY_CHECKS = 1;"))
            conn.commit()

        # Verify tables and row counts in the restored database
        insp = inspect(test_engine)
        restored_tables = insp.get_table_names()
        print(f"[SUCCESS] Restored {len(restored_tables)} tables successfully into `{DISPOSABLE_DB}`:")
        with test_engine.connect() as conn:
            for t in restored_tables:
                cnt = conn.execute(text(f"SELECT COUNT(1) FROM `{t}`")).scalar()
                print(f"    - `{t}`: {cnt} rows verified")

        print("[SUCCESS] Disaster recovery restoration test passed with 100% data fidelity.")

    finally:
        print(f"[*] Tearing down disposable test database `{DISPOSABLE_DB}`...")
        test_engine.dispose()
        with server_engine.connect() as conn:
            conn.execute(text(f"DROP DATABASE IF EXISTS `{DISPOSABLE_DB}`"))
        server_engine.dispose()
        print(f"[SUCCESS] Disposable database cleaned up. Live database remained untouched.")

if __name__ == "__main__":
    verify_restoration()
